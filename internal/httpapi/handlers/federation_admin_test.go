// TestFederationEnable_SetsFlagAndSelfRow asserts that enabling federation flips
// the project's isFederated flag and inserts the owner is_owner=1 self-row in
// federated_projects (US-1.1 AC1).
func TestFederationEnable_SetsFlagAndSelfRow(t *testing.T) {
	e := setupAPIEnv(t)
	ctx := createTestContext(t, e, "Work")
	p := createTestProject(t, e, ctx.ID, "Shared")
	if p.IsFederated {
		t.Fatalf("project should start non-federated")
	}

	resp, body := doReq(t, e.app, e.authedReq(t, http.MethodPost,
		fmt.Sprintf("/api/v1/projects/%d/federation/enable", p.ID), nil))
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("enable: got %d, want 200; body: %s", resp.StatusCode, body)
	}
	var got dto.ProjectDTO
	if err := json.Unmarshal(body, &got); err != nil {
		t.Fatalf("parse: %v", err)
	}
	if !got.IsFederated {
		t.Errorf("returned project isFederated: got false, want true")
	}

	// The owner self-row exists: is_owner=1, peer == origin == this instance.
	self, err := e.fedProjects.SelfRow(context.Background(), p.ID)
	if err != nil {
		t.Fatalf("self-row not found: %v", err)
	}
	if !self.IsOwner {
		t.Errorf("self-row is_owner: got false, want true")
	}
	if self.PeerInstanceURL != testBaseURL || self.OriginInstanceURL != testBaseURL {
		t.Errorf("self-row instance urls: peer=%q origin=%q, want both %q",
			self.PeerInstanceURL, self.OriginInstanceURL, testBaseURL)
	}
	if self.ProtocolVersion < 1 {
		t.Errorf("self-row protocol_version: got %d, want >= 1", self.ProtocolVersion)
	}
}

// TestFederationEnable_Idempotent asserts that enabling federation twice is a
// no-op the second time: still 200, no duplicate self-row, joined_at preserved
// (US-1.1 AC1 idempotency).
func TestFederationEnable_Idempotent(t *testing.T) {
	e := setupAPIEnv(t)
	ctx := createTestContext(t, e, "Work")
	p := createTestProject(t, e, ctx.ID, "Shared")

	enableURL := fmt.Sprintf("/api/v1/projects/%d/federation/enable", p.ID)
	resp, body := doReq(t, e.app, e.authedReq(t, http.MethodPost, enableURL, nil))
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("first enable: got %d, want 200; body: %s", resp.StatusCode, body)
	}
	first, err := e.fedProjects.SelfRow(context.Background(), p.ID)
	if err != nil {
		t.Fatalf("self-row after first enable: %v", err)
	}

	resp2, body2 := doReq(t, e.app, e.authedReq(t, http.MethodPost, enableURL, nil))
	if resp2.StatusCode != http.StatusOK {
		t.Fatalf("second enable: got %d, want 200; body: %s", resp2.StatusCode, body2)
	}

	rows, err := e.fedProjects.ListByProject(context.Background(), p.ID)
	if err != nil {
		t.Fatalf("list rows: %v", err)
	}
	if len(rows) != 1 {
		t.Errorf("federated_projects rows after double enable: got %d, want 1", len(rows))
	}
	second, err := e.fedProjects.SelfRow(context.Background(), p.ID)
	if err != nil {
		t.Fatalf("self-row after second enable: %v", err)
	}
	if !second.JoinedAt.Equal(first.JoinedAt) {
		t.Errorf("joined_at changed on idempotent re-enable: %v -> %v", first.JoinedAt, second.JoinedAt)
	}
}

// TestFederationEnable_KeypairExists asserts that enabling federation guarantees
// this instance has generated its trust-plane keypair (US-1.1 AC4).
func TestFederationEnable_KeypairExists(t *testing.T) {
	e := setupAPIEnv(t)
	ctx := createTestContext(t, e, "Work")
	p := createTestProject(t, e, ctx.ID, "Shared")

	// No keypair before enabling.
	if _, err := e.fedKeys.Get(context.Background()); !errors.Is(err, repo.ErrNotFound) {
		t.Fatalf("expected no keypair before enable, got err=%v", err)
	}

	resp, body := doReq(t, e.app, e.authedReq(t, http.MethodPost,
		fmt.Sprintf("/api/v1/projects/%d/federation/enable", p.ID), nil))
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("enable: got %d, want 200; body: %s", resp.StatusCode, body)
	}

	keys, err := e.fedKeys.Get(context.Background())
	if err != nil {
		t.Fatalf("keypair not generated by enable: %v", err)
	}
	if keys.PublicKey == "" || keys.NodeID == "" {
		t.Errorf("keypair incomplete: pub=%q node=%q", keys.PublicKey, keys.NodeID)
	}
}

// TestFederationEnable_ListReturnsFlag asserts that the projects.list payload
// carries isFederated so the UI can render the badge (US-1.1 AC2).
func TestFederationEnable_ListReturnsFlag(t *testing.T) {
	e := setupAPIEnv(t)
	ctx := createTestContext(t, e, "Work")
	p := createTestProject(t, e, ctx.ID, "Shared")

	resp, body := doReq(t, e.app, e.authedReq(t, http.MethodPost,
		fmt.Sprintf("/api/v1/projects/%d/federation/enable", p.ID), nil))
	if resp.StatusCode != http.StatusOK {
		t.Fatalf("enable: got %d, want 200; body: %s", resp.StatusCode, body)
	}

	listResp, listBody := doReq(t, e.app, e.authedReq(t, http.MethodGet, "/api/v1/projects/", nil))
	if listResp.StatusCode != http.StatusOK {
		t.Fatalf("list: got %d, want 200; body: %s", listResp.StatusCode, listBody)
	}
	var page dto.PagedResponse[dto.ProjectDTO]
	if err := json.Unmarshal(listBody, &page); err != nil {
		t.Fatalf("parse list: %v", err)
	}
	var found bool
	for _, item := range page.Items {
		if item.ID == p.ID {
			found = true
			if !item.IsFederated {
				t.Errorf("listed project isFederated: got false, want true")
			}
		}
	}
	if !found {
		t.Errorf("enabled project %d not present in list", p.ID)
	}
}

