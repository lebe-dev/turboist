// TestFederationEnable_KeyMissing asserts that when federation is NOT configured
// (no FEDERATION_KEY → nil service), the enable route returns
// CodeFederationKeyMissing rather than silently flipping the flag (US-1.1 AC4).
func TestFederationEnable_KeyMissing(t *testing.T) {
	dir := t.TempDir()
	d, err := db.Open(filepath.Join(dir, "nofed.db"))
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	t.Cleanup(func() { _ = d.Close() })
	if err := db.RunMigrations(context.Background(), d); err != nil {
		t.Fatalf("migrate: %v", err)
	}

	issuer := auth.NewJWTIssuer([]byte("test-secret-key-32-bytes-padding!"))
	users := repo.NewUserRepo(d)
	if _, err := users.Create(context.Background(), "admin", "h"); err != nil {
		t.Fatalf("seed user: %v", err)
	}
	apiTokens := repo.NewAPITokenRepo(d)
	salt := []byte("test-api-token-salt-32-bytes-pad!")
	deps := httpapi.Deps{JWTIssuer: issuer, UserRepo: users, APITokenRepo: apiTokens, APITokenSalt: salt}
	app := httpapi.NewApp(deps)
	api := httpapi.RegisterRoutes(app, deps)
	// Federation NOT configured: pass a nil service (mirrors FEDERATION_KEY unset).
	handlers.NewFederationAdminHandler(nil).Register(api.Group("", httpapi.RequireJWTAuth()))

	tok, _, err := issuer.Issue(1, 1)
	if err != nil {
		t.Fatalf("issue token: %v", err)
	}
	req := httptest.NewRequest(http.MethodPost, "/api/v1/projects/1/federation/enable", http.NoBody)
	req.Header.Set("Authorization", "Bearer "+tok)
	resp, err := app.Test(req)
	if err != nil {
		t.Fatalf("test: %v", err)
	}
	if resp.StatusCode != http.StatusConflict {
		t.Fatalf("enable without federation key: got %d, want 409", resp.StatusCode)
	}
	var env struct {
		Error struct {
			Code string `json:"code"`
		} `json:"error"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&env); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if env.Error.Code != httpapi.CodeFederationKeyMissing {
		t.Errorf("error code: got %q, want %q", env.Error.Code, httpapi.CodeFederationKeyMissing)
	}
}
